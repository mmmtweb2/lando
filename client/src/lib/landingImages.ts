// Landing-page photos on the client (README part 140): reading the stored `user_images` JSON, the
// srcset / alt / focal point of a photo, and the two layout decisions (how the opening image is
// shown, how the gallery is laid out for 1..12 photos of any orientation). Pure functions, no React,
// so scripts/test-landing-images.ts can pin them. The stored shape is documented in
// src/services/imageSlots.ts; the server and this file must agree on it.

export interface ImgMeta {
  alt?: string;
  w?: number;
  h?: number;
  sm?: string;
  smw?: number;
  pm?: string;
  pw?: number;
  ph?: number;
  fx?: number;
  fy?: number;
  logo?: boolean;
}

export type MetaMap = Record<string, ImgMeta>;

/** Same rule as src/services/imageSlots.ts promoteLegacyHero (array offsets: hero 0, about 1, services 2..7). */
export function promoteLegacyHero(arr: string[]): string[] {
  const out = arr.map((x) => (typeof x === 'string' ? x : ''));
  if (out[0]) return out;
  const services = out.slice(2, 8);
  const first = services.findIndex(Boolean);
  if (first < 0) return out;
  const hero = services[first];
  const rest = services.filter((_, i) => i !== first);
  while (rest.length < 6) rest.push('');
  out[0] = hero;
  rest.forEach((u, i) => { out[2 + i] = u; });
  return out;
}

/** img_meta of a parsed user_images value (object shape only); unknown or malformed entries are dropped. */
export function readImgMeta(parsed: unknown): MetaMap {
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return {};
  const raw = (parsed as { img_meta?: unknown }).img_meta;
  if (!raw || typeof raw !== 'object') return {};
  const out: MetaMap = {};
  const num = (v: unknown) => (typeof v === 'number' && isFinite(v) && v > 0 ? v : undefined);
  const str = (v: unknown) => (typeof v === 'string' && v ? v : undefined);
  for (const [url, v] of Object.entries(raw as Record<string, unknown>)) {
    if (!v || typeof v !== 'object') continue;
    const m = v as Record<string, unknown>;
    out[url] = {
      alt: str(m.alt), w: num(m.w), h: num(m.h), sm: str(m.sm), smw: num(m.smw),
      pm: str(m.pm), pw: num(m.pw), ph: num(m.ph),
      fx: typeof m.fx === 'number' ? m.fx : undefined, fy: typeof m.fy === 'number' ? m.fy : undefined,
      logo: m.logo === true ? true : undefined,
    };
  }
  return out;
}

// ─── One photo ────────────────────────────────────────────────────────────────

export function fallbackAlt(businessName: string): string {
  const name = (businessName ?? '').trim().replace(/\s+/g, ' ').slice(0, 60);
  return name ? `תמונה מהעבודה של ${name}` : 'תמונה מהעבודה שלנו';
}

/**
 * The alt text of a photo: the stored one; otherwise a plain contextual sentence; and "" (decorative)
 * for pictures generated by the AI image step, which carry no information of their own.
 */
export function altFor(info: ImgMeta | undefined, businessName: string, decorative = false): string {
  if (info?.alt) return info.alt;
  return decorative ? '' : fallbackAlt(businessName);
}

/** `small 640w, main 1200w`; undefined when the photo has no smaller copy (every photo stored before part 140). */
export function buildSrcSet(src: string, info: ImgMeta | undefined): string | undefined {
  if (!info?.sm || !info.smw || !info.w || info.smw >= info.w) return undefined;
  return `${info.sm} ${info.smw}w, ${src} ${info.w}w`;
}

/** CSS object-position from the stored focal point; undefined (browser default: centre) when unknown or a logo. */
export function focalPosition(info: ImgMeta | undefined): string | undefined {
  if (!info || info.logo || typeof info.fx !== 'number' || typeof info.fy !== 'number') return undefined;
  const c = (v: number) => Math.min(100, Math.max(0, Math.round(v)));
  return `${c(info.fx)}% ${c(info.fy)}%`;
}

/** A screen-sized pair of widths/heights to put on the <img> so the browser reserves the space before it loads. */
export function intrinsicSize(info: ImgMeta | undefined): { width?: number; height?: number } {
  return info?.w && info?.h ? { width: info.w, height: info.h } : {};
}

/** aspect ratio (w/h) of a photo; unknown photos count as a normal landscape picture. */
export function aspectOf(info: ImgMeta | undefined): number {
  return info?.w && info?.h ? info.w / info.h : 1.5;
}

// ─── The opening image ────────────────────────────────────────────────────────

/**
 * How the opening image is shown on a wide screen. On a phone it always fills the top of the page.
 *  cover  landscape (or unknown): the photo is the whole opening, the headline sits on it under a scrim
 *  split  portrait / squarish: a wide crop would cut the subject, so the photo takes one half, the
 *         headline the other
 */
export type HeroLayout = 'cover' | 'split';

export function planHero(info: ImgMeta | undefined): HeroLayout {
  if (!info?.w || !info?.h) return 'cover';
  return info.w / info.h >= 1.15 ? 'cover' : 'split';
}

// ─── The gallery ──────────────────────────────────────────────────────────────

export interface Span { c: number; r: number }
export interface GalleryTile {
  /** Position in the list of photos given to planGallery. */
  index: number;
  /** Cells taken on a phone (2 columns) and on a wide screen (3 columns). */
  m: Span;
  d: Span;
  /** The `sizes` attribute for this tile. */
  sizes: string;
}
export interface GalleryPlan {
  /** none: nothing to show; single / pair: simple, uncropped-looking boxes; grid: banded grid, no holes */
  kind: 'none' | 'single' | 'pair' | 'grid';
  /** single / pair: the box shape every photo is cropped to */
  box?: 'landscape' | 'portrait' | 'square';
  tiles: GalleryTile[];
}

const isPortrait = (a: number) => a < 0.9;
const isLandscape = (a: number) => a >= 1.15;

/** 2 columns (phones). Bands: W one wide, P a pair, T a tall one beside two small. Every band fills its rows. */
export function spansForPhone(aspects: number[]): Span[] {
  const out: Span[] = [];
  let i = 0;
  let prevWide = false;
  while (i < aspects.length) {
    const rem = aspects.length - i;
    const first = aspects[i];
    let band: 'W' | 'P' | 'T';
    if (rem === 1) band = 'W';
    else if (rem === 2) band = 'P';
    else if (rem === 3) band = isPortrait(first) ? 'T' : 'W';
    else if (isPortrait(first)) band = 'T';
    else band = !prevWide && first >= 1.3 ? 'W' : 'P';
    prevWide = band === 'W';
    if (band === 'W') { out.push({ c: 2, r: 2 }); i += 1; }
    else if (band === 'P') {
      const tall = isPortrait(aspects[i]) && isPortrait(aspects[i + 1]);
      out.push({ c: 1, r: tall ? 2 : 1 }, { c: 1, r: tall ? 2 : 1 });
      i += 2;
    } else { out.push({ c: 1, r: 2 }, { c: 1, r: 1 }, { c: 1, r: 1 }); i += 3; }
  }
  return out;
}

/** 3 columns (wide screens). Bands: F full width, D big + tall, R a row of three, B big + two small, T five (tall + four). */
export function spansForDesktop(aspects: number[]): Span[] {
  const out: Span[] = [];
  let i = 0;
  let flip = false;
  while (i < aspects.length) {
    const rem = aspects.length - i;
    const first = aspects[i];
    let band: 'F' | 'D' | 'R' | 'B' | 'T';
    if (rem === 1) band = 'F';
    else if (rem === 2 || rem === 4) band = 'D';
    else if (rem === 3) band = 'R';
    else if (rem === 5) band = isPortrait(first) ? 'T' : 'R';
    else if (rem === 6) band = 'B';
    else band = isPortrait(first) ? 'T' : 'B';
    if (band === 'F') { out.push({ c: 3, r: 2 }); i += 1; }
    else if (band === 'D') {
      out.push(...(flip ? [{ c: 1, r: 2 }, { c: 2, r: 2 }] : [{ c: 2, r: 2 }, { c: 1, r: 2 }]));
      flip = !flip; i += 2;
    } else if (band === 'R') {
      const tall = [aspects[i], aspects[i + 1], aspects[i + 2]].filter(isPortrait).length >= 2;
      out.push({ c: 1, r: tall ? 2 : 1 }, { c: 1, r: tall ? 2 : 1 }, { c: 1, r: tall ? 2 : 1 });
      i += 3;
    } else if (band === 'B') {
      out.push(...(flip ? [{ c: 1, r: 1 }, { c: 2, r: 2 }, { c: 1, r: 1 }] : [{ c: 2, r: 2 }, { c: 1, r: 1 }, { c: 1, r: 1 }]));
      flip = !flip; i += 3;
    } else { out.push({ c: 1, r: 2 }, { c: 1, r: 1 }, { c: 1, r: 1 }, { c: 1, r: 1 }, { c: 1, r: 1 }); i += 5; }
  }
  return out;
}

/** Cells covered by a list of spans: always a multiple of the column count, i.e. no gap at the end of the grid. */
export function cellsOf(spans: Span[]): number {
  return spans.reduce((n, s) => n + s.c * s.r, 0);
}

/**
 * How the gallery looks for these photos (given by aspect ratio, w/h). The decision depends on how
 * many there are and whether they are portrait or landscape:
 *   0  nothing, no section
 *   1  one box (not stretched), the box follows the photo's orientation
 *   2  two side by side, same box
 *   3+ a banded grid: whole rows only, so it never ends with an orphan gap, and a portrait photo gets a tall cell
 */
export function planGallery(aspects: number[]): GalleryPlan {
  const n = aspects.length;
  if (n === 0) return { kind: 'none', tiles: [] };
  const tileSizes = (m: Span, d: Span) => `(min-width: 860px) ${Math.round((d.c / 3) * 720)}px, ${Math.round((m.c / 2) * 100)}vw`;
  if (n === 1) {
    const a = aspects[0];
    return { kind: 'single', box: isPortrait(a) ? 'portrait' : isLandscape(a) ? 'landscape' : 'square',
      tiles: [{ index: 0, m: { c: 2, r: 1 }, d: { c: 3, r: 1 }, sizes: '(min-width: 860px) 640px, 100vw' }] };
  }
  if (n === 2) {
    const box = aspects.every(isLandscape) ? 'landscape' : 'portrait';
    return { kind: 'pair', box,
      tiles: aspects.map((_, index) => ({ index, m: { c: 1, r: 1 }, d: { c: 1, r: 1 }, sizes: '(min-width: 860px) 360px, 50vw' })) };
  }
  const m = spansForPhone(aspects);
  const d = spansForDesktop(aspects);
  return { kind: 'grid', tiles: aspects.map((_, index) => ({ index, m: m[index], d: d[index], sizes: tileSizes(m[index], d[index]) })) };
}

