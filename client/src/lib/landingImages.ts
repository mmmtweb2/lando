export const LOW_RES_MIN_SIDE = 800;
export const LOW_RES_MESSAGE = 'התמונה קטנה, בדף היא עלולה להיראות לא חדה. אפשר להמשיך, או להעלות תמונה גדולה יותר.';

/** The first photo opens the page: below this short side it looks soft on a phone. Never a reason to refuse. */
export function isLowRes(width: number, height: number): boolean {
  return Math.min(width, height) < LOW_RES_MIN_SIDE;
}
